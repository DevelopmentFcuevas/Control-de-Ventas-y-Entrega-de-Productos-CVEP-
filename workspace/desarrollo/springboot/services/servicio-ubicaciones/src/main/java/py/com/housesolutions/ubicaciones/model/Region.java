package py.com.housesolutions.ubicaciones.model;

/**
 * Regiones administrativas utilizadas para clasificar países a nivel interno.
 */
public enum Region {
    /** Zona Oriental del territorio nacional. */
    ORIENTAL,

    /** Zona Occidental del territorio nacional. */
    OCCIDENTAL,

    /** Para países donde la región no aplica o no está definida. */
    SIN_ESPECIFICAR
}
